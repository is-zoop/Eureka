import assert from "node:assert/strict";
import test from "node:test";
import { createServer } from "node:http";
import { mkdtemp, mkdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { createJiti } from "jiti";

test("real Chromium isolates chats, streams frames, accepts input and releases identity", { timeout: 120_000 }, async (t) => {
  const root = await mkdtemp(join(tmpdir(), "eureka-browser-")); const agent = join(root, "agent"); await mkdir(agent);
  const env = { PI_CODING_AGENT_DIR: agent, EUREKA_AUTH_HAZE_ISSUER: "https://haze.example", EUREKA_AUTH_CLIENT_ID: "test", EUREKA_AUTH_REDIRECT_URI: "http://localhost/callback", EUREKA_AUTH_SESSION_SECRET: "test-only-browser-session-secret-32" };
  const previous = Object.fromEntries(Object.keys(env).map((k) => [k, process.env[k]])); Object.assign(process.env, env);
  const jiti = createJiti(import.meta.url, { tsconfigPaths: true, alias: { "server-only": resolve("node_modules/next/dist/compiled/server-only/empty.js") } });
  const runtime = await jiti.import("./browser-runtime.ts"); const auth = await jiti.import("./auth/runtime-session.ts");
  const identity = { principal: { subject: "user-a", permissions: [] }, refreshToken: "test-only", providerId: "haze-oidc", expiresAt: Date.now() + 100_000 };
  await auth.writeRuntimeHazeSession(identity);
  const owner = runtime.browserOwner(env.EUREKA_AUTH_HAZE_ISSUER, "user-a");
  const requests = [];
  const server = createServer((req, res) => {
    requests.push({ path: req.url, auth: req.headers.authorization, cookie: req.headers.cookie });
    if (req.url.startsWith("/broken")) { req.socket.destroy(); return; }
    if (req.url.startsWith("/denied")) res.statusCode = 403;
    if (req.url.startsWith("/cached-probe")) res.setHeader("Cache-Control", "public, max-age=3600");
    res.setHeader("Content-Type", "text/html");
    if (req.url === "/cookie") res.setHeader("Set-Cookie", "selection=one; HttpOnly; SameSite=Strict; Path=/");
    res.end('<!doctype html><title>Selection fixture</title><input id="query" style="width:300px;height:40px"><button onclick="window.open(\'/popup\')">Popup</button><a href="/next">Next</a><script>history.replaceState(null,"",location.pathname)</script>');
  });
  await new Promise((done) => server.listen(0, "127.0.0.1", done));
  const url = `http://127.0.0.1:${server.address().port}`;
  let unsubscribe = () => {};
  t.after(async () => { unsubscribe(); await runtime.closeSessionBrowsers("one"); await runtime.closeSessionBrowsers("two"); await runtime.closeSessionBrowsers("three"); await runtime.closeSessionBrowsers("native"); await auth.clearRuntimeHazeSession(); for (const [k, v] of Object.entries(previous)) { if (v === undefined) delete process.env[k]; else process.env[k] = v; } server.closeAllConnections(); await new Promise((done) => server.close(done)); await rm(root, { recursive: true, force: true }); });
  assert.equal(await runtime.browserReady(), true, "run npm run browser:install before this integration test");
  const events = []; unsubscribe = runtime.subscribeBrowser(owner, "one", (event) => events.push(event), true);
  const [opened, duplicate] = await Promise.all([runtime.openBrowser(owner, "one", `${url}/cookie#launch=test-only`, "plugin/business"), runtime.openBrowser(owner, "two", `${url}/`, "other")]);
  assert.ok(opened.tabId && duplicate.tabId);
  const entries = [...globalThis.__eurekaBrowserRuntime.entries.values()];
  assert.equal(entries.length, 2);
  const first = entries.find((entry) => entry.sessionId === "one"), second = entries.find((entry) => entry.sessionId === "two");
  assert.notEqual(first.context, second.context);
  assert.equal((await second.context.cookies()).length, 0);
  assert.equal((await first.context.cookies())[0].sameSite, "Strict");
  assert.equal(requests.some((request) => request.auth), false);
  const action = (value) => runtime.browserAction(owner, "one", { tabId: opened.tabId, ...value });
  await action({ action: "resize", width: 800, height: 600 });
  await action({ action: "mouse", kind: "mousePressed", x: 80, y: 30, button: "left", buttons: 1 });
  await action({ action: "mouse", kind: "mouseReleased", x: 80, y: 30, button: "left", buttons: 0 });
  await action({ action: "text", text: "中文选数" });
  const page = first.tabs.get(opened.tabId).page;
  assert.equal(await page.locator("#query").inputValue(), "中文选数");
  await action({ action: "key", kind: "keyDown", key: "a", code: "KeyA", modifiers: 2 });
  await action({ action: "key", kind: "keyUp", key: "a", code: "KeyA", modifiers: 2 });
  await action({ action: "key", kind: "keyDown", key: "Backspace", code: "Backspace", modifiers: 0 });
  assert.equal(await page.locator("#query").inputValue(), "");
  await action({ action: "key", kind: "keyDown", key: "A", code: "KeyA", modifiers: 0 });
  assert.equal(await page.locator("#query").inputValue(), "A");
  await action({ action: "navigate", url: `${url}/next` }); await action({ action: "back" });
  assert.match(page.url(), /\/cookie$/);
  const reused = await runtime.openBrowser(owner, "one", `${url}/cookie#launch=new`, "plugin/business");
  assert.equal(reused.tabId, opened.tabId); assert.equal(first.tabs.size, 1);
  await action({ action: "navigate", url: `${url}/next` });
  await runtime.openBrowser(owner, "one", `${url}/cookie`, "plugin/business", { resume: true });
  assert.match(page.url(), /\/next$/, "resume preserves the page reached during manual login/navigation");
  assert.equal(first.tabs.size, 1);
  const changed = await runtime.openBrowser(owner, "one", `${url}/changed`, "automation:changed", { resume: true });
  assert.notEqual(changed.tabId, opened.tabId, "a changed destination must open its own target");
  await runtime.browserAction(owner, "one", { action: "close-tab", tabId: changed.tabId });
  const retryTab = await runtime.openBrowser(owner, "one", "about:blank", "retry", { resume: true });
  await runtime.openBrowser(owner, "one", `${url}/retry`, "retry", { resume: true });
  assert.match(first.tabs.get(retryTab.tabId).page.url(), /\/retry$/, "an incomplete initial open remains retryable");
  await runtime.browserAction(owner, "one", { action: "close-tab", tabId: retryTab.tabId });
  const parallel = await Promise.all([runtime.openBrowser(owner, "one", `${url}/`, "new-business"), runtime.openBrowser(owner, "one", `${url}/next`, "new-business")]);
  assert.equal(parallel[0].tabId, parallel[1].tabId, "concurrent opens reuse one business tab");
  await runtime.browserAction(owner, "one", { action: "close-tab", tabId: parallel[0].tabId });
  await page.locator("button").click();
  await assertEventually(() => first.tabs.size === 2);
  const popupId = first.activeTabId;
  await runtime.openBrowser(owner, "one", `${url}/cookie`, "plugin/business", { resume: true });
  assert.equal(first.activeTabId, popupId, "resuming preserves an active login popup");
  await assertEventually(() => events.some((event) => event.type === "frame" && event.data.length > 100));
  assert.equal(JSON.stringify(runtime.browserState(owner, "one")).includes("launch="), false);
  unsubscribe(); unsubscribe = () => {};
  await assertEventually(() => [...first.tabs.values()].every((tab) => !tab.streaming));
  for (const invalid of ["file:///C:/secret", "javascript:alert(1)", "http://user:pass@localhost/"]) assert.throws(() => runtime.browserUrl(invalid));
  await assert.rejects(runtime.browserAction(runtime.browserOwner(env.EUREKA_AUTH_HAZE_ISSUER, "other"), "one", { action: "reload", tabId: opened.tabId }), /身份/);
  // Upgrade just the automation session; existing plugin contexts remain alive.
  await runtime.openBrowser(owner, "native", `${url}/old`, "old");
  const oldNative = [...globalThis.__eurekaBrowserRuntime.entries.values()].find(e => e.sessionId === "native");
  const [nativeOpen, nativeDuplicate] = await Promise.all([
    runtime.openBrowser(owner, "native", `${url}/cookie`, "native", { resume: true, presentation: "window" }),
    runtime.openBrowser(owner, "native", `${url}/cookie`, "native", { resume: true, presentation: "window" }),
  ]);
  assert.equal(nativeOpen.tabId, nativeDuplicate.tabId);
  const native = [...globalThis.__eurekaBrowserRuntime.entries.values()].find(e => e.sessionId === "native");
  assert.notEqual(native.context, oldNative.context);
  assert.equal(native.presentation, "window");
  assert.equal(native.tabs.size, 1, "native page events and explicit opens must deduplicate");
  assert.notEqual(native.context.browser(), first.context.browser());
  const nativeTab = native.tabs.get(nativeOpen.tabId);
  assert.equal(nativeTab.page.viewportSize(), null, "panel resizing cannot change the native viewport");
  assert.equal(await nativeTab.page.evaluate(() => navigator.webdriver), false, "explicit-port native launch preserves the browser's ordinary navigator value");
  // Verify real browser cache behavior.
  await nativeTab.page.evaluate(async () => { await fetch("/cached-probe?mode=native"); await fetch("/cached-probe?mode=native"); });
  assert.equal(requests.filter(r => r.path === "/cached-probe?mode=native").length, 1);
  await page.evaluate(async () => { await fetch("/cached-probe?mode=panel"); await fetch("/cached-probe?mode=panel"); });
  assert.equal(requests.filter(r => r.path === "/cached-probe?mode=panel").length, 2, "plugin panel routing remains unchanged");
  await assert.rejects(runtime.browserAction(owner, "native", { action: "navigate", tabId: nativeTab.id, url: "file:///C:/secret" }), /HTTP|用户名|地址/);
  const nativeEvents = [];
  const stopNative = runtime.subscribeBrowser(owner, "native", event => nativeEvents.push(event), true);
  assert.equal(native.timer, undefined, "a visible window must not expire when its panel is hidden");
  assert.equal(nativeTab.streaming, false, "manual window does not stream credential pictures");
  assert.equal(native.nativeWindow.debugPortMode, "explicit");
  assert.equal(native.requestRouting, false);
  await nativeTab.page.locator("#query").fill("直接窗口输入");
  await nativeTab.page.goto(`${url}/next`);
  await runtime.openBrowser(owner, "native", `${url}/cookie`, "native", { resume: true, presentation: "window" });
  assert.match(nativeTab.page.url(), /\/next$/);
  assert.ok((await native.context.cookies()).some(c => c.name === "selection"));
  await assert.rejects(runtime.browserAction(owner, "native", { action: "resize", tabId: nativeTab.id, width: 300, height: 200 }), /独立浏览器/);
  await assert.rejects(runtime.browserAction(owner, "native", { action: "text", tabId: nativeTab.id, text: "转发" }), /独立浏览器/);
  const { windowId } = await nativeTab.cdp.send("Browser.getWindowForTarget");
  await nativeTab.cdp.send("Browser.setWindowBounds", { windowId, bounds: { windowState: "minimized" } });
  await runtime.browserAction(owner, "native", { action: "show-window", tabId: nativeTab.id });
  assert.notEqual((await nativeTab.cdp.send("Browser.getWindowForTarget")).bounds.windowState, "minimized");
  const manualTab = await native.context.newPage();
  await manualTab.goto(`${url}/manual`);
  await assertEventually(() => native.tabs.size === 2);
  await manualTab.close();
  assert.equal(nativeEvents.some(e => e.type === "frame"), false);
  // Embed the accepted native session without restarting it or losing sign-in.
  const embedded = await runtime.openBrowser(owner, "native", `${url}/cookie`, "native", { resume: true, presentation: "embedded" });
  assert.equal(embedded.tabId, nativeTab.id);
  assert.equal(native.context, [...globalThis.__eurekaBrowserRuntime.entries.values()].find(e => e.sessionId === "native").context);
  assert.match(nativeTab.page.url(), /\/next$/);
  assert.equal(runtime.browserState(owner, "native").presentation, "embedded");
  assert.ok((await native.context.cookies()).some(c => c.name === "selection"));
  assert.equal((await nativeTab.cdp.send("Browser.getWindowForTarget")).bounds.windowState, "minimized");
  await assertEventually(() => nativeEvents.some(e => e.type === "frame" && e.tabId === nativeTab.id && e.data.length > 100));
  const embeddedAction = value => runtime.browserAction(owner, "native", { tabId: nativeTab.id, ...value });
  await embeddedAction({ action: "resize", width: 800, height: 600 });
  assert.deepEqual(await nativeTab.page.evaluate(() => [innerWidth, innerHeight]), [800, 600]);
  assert.equal(await nativeTab.page.evaluate(() => navigator.webdriver), false);
  await embeddedAction({ action: "mouse", kind: "mousePressed", x: 80, y: 30, buttons: 1 });
  await embeddedAction({ action: "mouse", kind: "mouseReleased", x: 80, y: 30, buttons: 0 });
  await embeddedAction({ action: "text", text: "内置中文输入" });
  assert.equal(await nativeTab.page.locator("#query").inputValue(), "内置中文输入");
  await embeddedAction({ action: "key", kind: "keyDown", key: "a", code: "KeyA", modifiers: 2 });
  await embeddedAction({ action: "key", kind: "keyDown", key: "Backspace", code: "Backspace", modifiers: 0 });
  assert.equal(await nativeTab.page.locator("#query").inputValue(), "");
  await nativeTab.page.evaluate(async () => { await fetch("/cached-probe?mode=embedded"); await fetch("/cached-probe?mode=embedded"); });
  assert.equal(requests.filter(r => r.path === "/cached-probe?mode=embedded").length, 1);
  await embeddedAction({ action: "show-window" });
  assert.equal(native.presentation, "window");
  assert.equal(nativeTab.streaming, false);
  assert.notEqual((await nativeTab.cdp.send("Browser.getWindowForTarget")).bounds.windowState, "minimized");
  assert.notDeepEqual(await nativeTab.page.evaluate(() => [innerWidth, innerHeight]), [800, 600], "native window clears panel metrics");
  await embeddedAction({ action: "show-panel" });
  assert.equal(native.presentation, "embedded");
  const embeddedPopup = await native.context.newPage();
  await embeddedPopup.goto(`${url}/embedded-popup`);
  await assertEventually(() => native.tabs.size === 2);
  const embeddedPopupId = native.activeTabId;
  await assertEventually(() => nativeEvents.some(e => e.type === "frame" && e.tabId === embeddedPopupId));
  const frameCount = nativeEvents.filter(e => e.type === "frame" && e.tabId === nativeTab.id).length;
  await embeddedAction({ action: "select-tab" });
  assert.equal(native.activeTabId, nativeTab.id);
  await assertEventually(() => nativeEvents.filter(e => e.type === "frame" && e.tabId === nativeTab.id).length > frameCount);
  assert.equal((await nativeTab.cdp.send("Browser.getWindowForTarget")).bounds.windowState, "minimized");
  await embeddedAction({ action: "mouse", kind: "mousePressed", x: 80, y: 30, buttons: 1 });
  await embeddedAction({ action: "mouse", kind: "mouseReleased", x: 80, y: 30, buttons: 0 });
  await embeddedAction({ action: "text", text: "后台标签输入" });
  assert.equal(await nativeTab.page.locator("#query").inputValue(), "后台标签输入");
  await embeddedPopup.close();
  stopNative();
  await assertEventually(() => !nativeTab.streaming);
  assert.equal(native.timer, undefined);
  await nativeTab.page.close();
  await assertEventually(() => !runtime.hasBrowser(owner, "native"));
  assert.ok(runtime.hasBrowser(owner, "one"), "closing the native window must not close a plugin browser");
  await runtime.openBrowser(owner, "native", `${url}/reopened`, "native", { presentation: "embedded" });
  const reopened = [...globalThis.__eurekaBrowserRuntime.entries.values()].find(e => e.sessionId === "native");
  assert.equal((await reopened.context.cookies()).length, 0, "closing the last window clears its temporary sign-in");
  const reopenedTab = [...reopened.tabs.values()][0];
  assert.equal(await reopenedTab.page.evaluate(() => navigator.webdriver), false);
  assert.equal((await reopenedTab.cdp.send("Browser.getWindowForTarget")).bounds.windowState, "minimized");
  assert.equal(reopened.nativeWindow.debugPortMode, "explicit");
  await runtime.browserAction(owner, "automation:empty-panel", { action: "new-tab" });
  try {
    assert.equal(runtime.browserState(owner, "automation:empty-panel").presentation, "embedded", "new tab in an empty automation panel keeps the accepted launcher");
  } finally { await runtime.closeSessionBrowsers("automation:empty-panel"); }
  await auth.writeRuntimeHazeSession({ ...identity, principal: { subject: "other", permissions: [] } });
  runtime.clearBrowserIdentity(runtime.browserOwner(env.EUREKA_AUTH_HAZE_ISSUER, "other"));
  await assertEventually(() => globalThis.__eurekaBrowserRuntime.entries.size === 0);
  const nextOwner = runtime.browserOwner(env.EUREKA_AUTH_HAZE_ISSUER, "other");
  await runtime.openBrowser(nextOwner, "three", `${url}/`, "new-identity");
  assert.equal(runtime.browserState(nextOwner, "three").error, undefined, "old Chromium teardown cannot invalidate a newly launched instance");
  await runtime.closeSessionBrowsers("three");
});
async function assertEventually(check) { const end = Date.now() + 10000; while (!check()) { if (Date.now() > end) assert.fail("browser state did not settle"); await new Promise((done) => setTimeout(done, 50)); } }
