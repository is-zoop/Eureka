import assert from "node:assert/strict";
import test from "node:test";
import { createServer } from "node:http";
import { mkdtemp, mkdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { createJiti } from "jiti";

test("real Chromium isolates chats, streams frames, accepts input and releases identity", { timeout: 120_000 }, async (t) => {
  const root = await mkdtemp(join(tmpdir(), "eureka-browser-")); const agent = join(root, "agent"); await mkdir(agent);
  const env = { PI_CODING_AGENT_DIR: agent, EUREKA_AUTH_HAZE_ISSUER: "https://haze.example", EUREKA_AUTH_CLIENT_ID: "test", EUREKA_AUTH_REDIRECT_URI: "http://localhost/callback", EUREKA_AUTH_SESSION_SECRET: "test-only-browser-session-secret-32" };
  const previous = Object.fromEntries(Object.keys(env).map((k) => [k, process.env[k]])); Object.assign(process.env, env);
  const jiti = createJiti(import.meta.url, { tsconfigPaths: true, alias: { "server-only": resolve("node_modules/next/dist/compiled/server-only/empty.js") } });
  const runtime = await jiti.import("./browser-runtime.ts"); const auth = await jiti.import("./auth/runtime-session.ts");
  const identity = { principal: { subject: "user-a", permissions: [] }, refreshToken: "test-only", providerId: "haze-oidc", expiresAt: Date.now() + 100_000 };
  await auth.writeRuntimeHazeSession(identity);
  const owner = runtime.browserOwner(env.EUREKA_AUTH_HAZE_ISSUER, "user-a");
  const requests = [];
  const server = createServer((req, res) => {
    requests.push({ path: req.url, auth: req.headers.authorization, cookie: req.headers.cookie });
    res.setHeader("Content-Type", "text/html");
    if (req.url === "/cookie") res.setHeader("Set-Cookie", "selection=one; HttpOnly; SameSite=Strict; Path=/");
    res.end('<!doctype html><title>Selection fixture</title><input id="query" style="width:300px;height:40px"><button onclick="window.open(\'/popup\')">Popup</button><a href="/next">Next</a><script>history.replaceState(null,"",location.pathname)</script>');
  });
  await new Promise((done) => server.listen(0, "127.0.0.1", done));
  const url = `http://127.0.0.1:${server.address().port}`;
  let unsubscribe = () => {};
  t.after(async () => { unsubscribe(); await runtime.closeSessionBrowsers("one"); await runtime.closeSessionBrowsers("two"); await runtime.closeSessionBrowsers("three"); await auth.clearRuntimeHazeSession(); for (const [k, v] of Object.entries(previous)) { if (v === undefined) delete process.env[k]; else process.env[k] = v; } server.closeAllConnections(); await new Promise((done) => server.close(done)); await rm(root, { recursive: true, force: true }); });
  assert.equal(await runtime.browserReady(), true, "run npm run browser:install before this integration test");
  const events = []; unsubscribe = runtime.subscribeBrowser(owner, "one", (event) => events.push(event), true);
  const [opened, duplicate] = await Promise.all([runtime.openBrowser(owner, "one", `${url}/cookie#launch=test-only`, "plugin/business"), runtime.openBrowser(owner, "two", `${url}/`, "other")]);
  assert.ok(opened.tabId && duplicate.tabId);
  const entries = [...globalThis.__eurekaBrowserRuntime.entries.values()];
  assert.equal(entries.length, 2);
  const first = entries.find((entry) => entry.sessionId === "one"), second = entries.find((entry) => entry.sessionId === "two");
  assert.notEqual(first.context, second.context);
  assert.equal((await second.context.cookies()).length, 0);
  assert.equal((await first.context.cookies())[0].sameSite, "Strict");
  assert.equal(requests.some((request) => request.auth), false);
  const action = (value) => runtime.browserAction(owner, "one", { tabId: opened.tabId, ...value });
  await action({ action: "resize", width: 800, height: 600 });
  await action({ action: "mouse", kind: "mousePressed", x: 80, y: 30, button: "left", buttons: 1 });
  await action({ action: "mouse", kind: "mouseReleased", x: 80, y: 30, button: "left", buttons: 0 });
  await action({ action: "text", text: "中文选数" });
  const page = first.tabs.get(opened.tabId).page;
  assert.equal(await page.locator("#query").inputValue(), "中文选数");
  await action({ action: "key", kind: "keyDown", key: "a", code: "KeyA", modifiers: 2 });
  await action({ action: "key", kind: "keyUp", key: "a", code: "KeyA", modifiers: 2 });
  await action({ action: "key", kind: "keyDown", key: "Backspace", code: "Backspace", modifiers: 0 });
  assert.equal(await page.locator("#query").inputValue(), "");
  await action({ action: "key", kind: "keyDown", key: "A", code: "KeyA", modifiers: 0 });
  assert.equal(await page.locator("#query").inputValue(), "A");
  await action({ action: "navigate", url: `${url}/next` }); await action({ action: "back" });
  assert.match(page.url(), /\/cookie$/);
  const reused = await runtime.openBrowser(owner, "one", `${url}/cookie#launch=new`, "plugin/business");
  assert.equal(reused.tabId, opened.tabId); assert.equal(first.tabs.size, 1);
  const parallel = await Promise.all([runtime.openBrowser(owner, "one", `${url}/`, "new-business"), runtime.openBrowser(owner, "one", `${url}/next`, "new-business")]);
  assert.equal(parallel[0].tabId, parallel[1].tabId, "concurrent opens reuse one business tab");
  await runtime.browserAction(owner, "one", { action: "close-tab", tabId: parallel[0].tabId });
  await page.locator("button").click();
  await assertEventually(() => first.tabs.size === 2);
  await assertEventually(() => events.some((event) => event.type === "frame" && event.data.length > 100));
  assert.equal(JSON.stringify(runtime.browserState(owner, "one")).includes("launch="), false);
  unsubscribe(); unsubscribe = () => {};
  await assertEventually(() => [...first.tabs.values()].every((tab) => !tab.streaming));
  for (const invalid of ["file:///C:/secret", "javascript:alert(1)", "http://user:pass@localhost/"]) assert.throws(() => runtime.browserUrl(invalid));
  await assert.rejects(runtime.browserAction(runtime.browserOwner(env.EUREKA_AUTH_HAZE_ISSUER, "other"), "one", { action: "reload", tabId: opened.tabId }), /身份/);
  await auth.writeRuntimeHazeSession({ ...identity, principal: { subject: "other", permissions: [] } });
  runtime.clearBrowserIdentity(runtime.browserOwner(env.EUREKA_AUTH_HAZE_ISSUER, "other"));
  await assertEventually(() => globalThis.__eurekaBrowserRuntime.entries.size === 0);
  const nextOwner = runtime.browserOwner(env.EUREKA_AUTH_HAZE_ISSUER, "other");
  await runtime.openBrowser(nextOwner, "three", `${url}/`, "new-identity");
  assert.equal(runtime.browserState(nextOwner, "three").error, undefined, "old Chromium teardown cannot invalidate a newly launched instance");
  await runtime.closeSessionBrowsers("three");
});
async function assertEventually(check) { const end = Date.now() + 10000; while (!check()) { if (Date.now() > end) assert.fail("browser state did not settle"); await new Promise((done) => setTimeout(done, 50)); } }
