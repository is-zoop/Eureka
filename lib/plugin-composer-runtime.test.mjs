import assert from "node:assert/strict";
import test from "node:test";
import { mkdir, mkdtemp, rm, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { createJiti } from "jiti";
import { fixtureZip, pluginFiles } from "./haze-plugin-fixture.mjs";

test("composer selections and browser handoff validate loaded plugin identity", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "eureka-composer-"));
  const agent = join(root, "agent"), cwd = join(root, "project"); await mkdir(agent); await mkdir(cwd);
  const env = { PI_CODING_AGENT_DIR: agent, EUREKA_AUTH_HAZE_ISSUER: "https://haze.example", EUREKA_AUTH_CLIENT_ID: "test-client", EUREKA_AUTH_REDIRECT_URI: "http://localhost/callback", EUREKA_AUTH_SESSION_SECRET: "test-only-composer-session-secret-32" };
  const previous = Object.fromEntries(Object.keys(env).map((k) => [k, process.env[k]])); Object.assign(process.env, env);
  const fetch = globalThis.fetch;
  globalThis.fetch = async (url) => String(url).endsWith("/access-prompt") ? Response.json({ data: { download_url: "https://haze.example/download" } }) : new Response(fixtureZip(pluginFiles({ requestUserInput: true })));
  t.after(async () => { globalThis.fetch = fetch; for (const [k, v] of Object.entries(previous)) { if (v === undefined) delete process.env[k]; else process.env[k] = v; } await rm(root, { recursive: true, force: true }); });
  const jiti = createJiti(import.meta.url, { tsconfigPaths: true, alias: { "server-only": resolve("node_modules/next/dist/compiled/server-only/empty.js") } });
  const install = await jiti.import("./haze-plugin-install.ts"), resources = await jiti.import("./haze-plugin-resources.ts"), registry = await jiti.import("./haze-registry.ts");
  const composer = await jiti.import("./composer-plugins.ts"), auth = await jiti.import("./auth/runtime-session.ts"), handoff = await jiti.import("./plugin-browser.ts");
  const session = { principal: { subject: "user-a", permissions: ["page.marketplace"] }, refreshToken: "test-only", providerId: "haze-oidc", expiresAt: Date.now() + 10000 };
  const input = { cwd, scope: "project", capabilityId: "42", name: "Atlas", version: "2.1.0", operation: "install", session, accessToken: "test-only" };
  const prepared = await install.prepareOrganizationPlugin(input);
  assert.equal(prepared.capabilities.requestUserInput, true);
  await install.commitOrganizationPlugin({ ...input, preparationToken: prepared.preparationToken, approveAddresses: true });
  await auth.writeRuntimeHazeSession(session);
  const item = registry.effectivePlugins(cwd)[0], server = resources.pluginMcpName(item, "atlas");
  const skills = resources.applyOrganizationPluginSkills(cwd, { skills: [], diagnostics: [] }).skills;
  resources.setPluginSnapshot("chat", cwd, [{ capabilityId: "42", source: item.plugin.source, digest: item.plugin.digest, root: item.plugin.root, servers: [server], capabilities: item.plugin.manifest.capabilities }]);
  const plugin = composer.listComposerPlugins(cwd, item.plugin.source, "user-a", "chat")[0];
  const task = { id: "atlas-task", clarificationEnabled: false, plugins: [plugin], owner: { source: item.plugin.source, subject: "user-a" } };
  assert.equal(composer.taskAllowsClarification(cwd, "chat", task), true);
  assert.deepEqual(composer.taskPluginSelection(cwd, "chat", undefined, skills, "普通聊天中提及 atlas-ask"), []);
  const skillSelection = composer.taskPluginSelection(cwd, "chat", undefined, skills, "/skill:atlas-ask 查询");
  assert.equal(skillSelection[0].capabilityId, plugin.capabilityId);
  assert.equal(composer.taskAllowsClarification(cwd, "chat", { ...task, plugins: [] }), false);
  assert.equal(composer.taskAllowsClarification(cwd, "other-chat", task), false);
  assert.equal(composer.taskAllowsClarification(cwd, "chat", { ...task, plugins: [{ ...plugin, digest: "stale" }] }), false);
  assert.deepEqual(composer.taskPluginSelection(cwd, "chat", undefined, [{ name: "atlas-ask", filePath: join(cwd, "local-skill", "SKILL.md") }], "/skill:atlas-ask 查询"), []);

  assert.equal(plugin.state, "loaded"); assert.equal(plugin.skills.length, 2);
  assert.equal(plugin.description, "atlas-ask", "menu description must not include version or runtime metadata");
  const expanded = composer.prepareSelectedPlugins(cwd, "chat", [plugin], skills, "查询");
  assert.match(expanded, /atlas-menu/); assert.match(expanded, /MCP server namespaces/);
  assert.throws(() => composer.prepareSelectedPlugins(cwd, "chat", [{ ...plugin, digest: "changed" }], skills, "查询"), /已更改/);
  assert.throws(() => composer.prepareSelectedPlugins(cwd, "chat", [plugin], [], "查询"), /冲突/);
  const calls = [];
  const open = async (...args) => { calls.push(args); return { tabId: "tab" }; };
  const payload = { session_id: "business", scope_revision: 3, browser_url: "http://localhost:3000/selector#launch=secret" };
  const event = { toolName: "mcp", toolCallId: "call", isError: false, details: { server, tool: "open_selection_menu" }, content: [{ type: "text", text: JSON.stringify(payload) }] };
  for (const toolName of ["mcp", `${server}_open_selection_menu`]) {
    const result = await handoff.handoffPluginBrowserResult({ ...event, toolName }, cwd, "chat", open);
    assert.equal(result.isError, false); assert.match(result.content[0].text, /"scope_revision":3/); assert.ok(!JSON.stringify(result).includes("secret"));
  }
  assert.equal(calls.length, 2);
  const structured = await handoff.handoffPluginBrowserResult({ ...event, details: { server, tool: "open_selection_menu", mcpResult: { structuredContent: payload } }, content: [] }, cwd, "chat", open);
  assert.equal(structured.details.browserPanel.status, "opened");
  const envelope = { data: payload, request_id: "atlas-request" };
  for (const structuredContent of [undefined, envelope]) {
    const wrapped = await handoff.handoffPluginBrowserResult({ ...event, details: { ...event.details, mcpResult: structuredContent ? { structuredContent } : undefined }, content: [{ type: "text", text: JSON.stringify(envelope) }] }, cwd, "chat", open);
    const response = JSON.parse(wrapped.content[0].text);
    assert.equal(response.request_id, "atlas-request");
    assert.equal(response.data.session_id, payload.session_id);
    assert.equal(response.data.scope_revision, payload.scope_revision);
    assert.equal(response.data.browser_panel.status, "opened");
    assert.equal(response.data.browser_url, undefined);
    assert.ok(!JSON.stringify(wrapped).includes("secret"));
    assert.ok(calls.at(-1)[3].endsWith("/business"));
  }
  const atlasError = { error: { code: "INTERNAL_ERROR", message: "服务内部错误" }, request_id: "failed-request" };
  assert.equal(await handoff.handoffPluginBrowserResult({ ...event, isError: true, content: [{ type: "text", text: JSON.stringify(atlasError) }] }, cwd, "chat", open), undefined);
  const failed = await handoff.handoffPluginBrowserResult(event, cwd, "chat", async () => { throw new Error("sensitive launch URL"); });
  assert.equal(failed.isError, true); assert.ok(!JSON.stringify(failed).includes("sensitive"));
  assert.equal(await handoff.handoffPluginBrowserResult({ ...event, isError: true }, cwd, "chat", open), undefined);
  assert.equal(await handoff.handoffPluginBrowserResult({ ...event, details: { server: "unregistered" } }, cwd, "chat", open), undefined);
  const handlers = {};
  handoff.installPluginBrowserHandoff({ on: (name, handler) => { handlers[name] = handler; } }, open);
  const context = { cwd, sessionManager: { getSessionId: () => "chat" } };
  const before = calls.length;
  await Promise.all([handlers.tool_result(event, context), handlers.tool_result(event, context)]);
  assert.equal(calls.length, before + 1, "one live tool result opens only once");
  handlers.session_shutdown();
  await handlers.tool_result(event, context);
  assert.equal(calls.length, before + 2);

  const manifestPath = join(item.plugin.root, "plugin.json");
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  manifest.extensions["com.eureka"].composer = { selectionMode: "persistent" };
  await writeFile(manifestPath, JSON.stringify(manifest));
  assert.equal(composer.listComposerPlugins(cwd, item.plugin.source, "user-a", "chat")[0].selectionMode, "persistent", "local composer edits are read without granting new capabilities");
  const { ClarificationRuntime } = await jiti.import("./clarification-runtime.ts");
  const { persistentPluginSelectionError, installPluginSelectionRuntime } = await jiti.import("./plugin-selection-runtime.ts");
  const manager = { getSessionId: () => "chat", getEntries: () => [], appendCustomEntry() {} };
  const runtime = new ClarificationRuntime(manager, () => {});
  const ctx = { cwd, sessionManager: manager };
  assert.match(persistentPluginSelectionError(ctx, server), /选择/);
  runtime.task = task;
  assert.equal(persistentPluginSelectionError(ctx, server), undefined);
  assert.equal(composer.taskAllowsClarification(cwd, "chat", runtime.task), true);
  assert.equal(persistentPluginSelectionError(ctx, "unrelated-mcp"), undefined);
  const selectionHandlers = {}, broker = new Map();
  let activeTools = ["mcp", "read"];
  installPluginSelectionRuntime({ on: (name, fn) => { selectionHandlers[name] = fn; }, events: { on: (name, fn) => { broker.set(name, fn); return () => broker.delete(name); } }, getActiveTools: () => activeTools });
  selectionHandlers.session_start({}, ctx);
  const listener = broker.get("pi-mcp-adapter:tool-approval-request");
  for (const origin of ["proxy", "direct", "script", "resource", "iframe"]) {
    let handler;
    listener({ serverName: server, origin, claim: (candidate) => { handler = candidate; return true; } });
    assert.equal(handler, undefined, "selection does not bypass existing MCP approval policies");
    runtime.task = { ...task, id: "next-message", plugins: [] };
    listener({ serverName: server, origin, claim: (candidate) => { handler = candidate; return true; } });
    assert.equal(handler(), "deny", `${origin} cannot reuse a deselected plugin`);
    assert.equal(selectionHandlers.tool_call({ toolName: "read", input: { path: skills[0].filePath } }, ctx).block, true);
    runtime.task = task;
    assert.equal(selectionHandlers.tool_call({ toolName: "read", input: { path: skills[0].filePath } }, ctx), undefined);
  }
  assert.match(selectionHandlers.before_agent_start({}, ctx).message.content, /SELECTED/);
  runtime.task = { ...task, plugins: [] };
  assert.match(selectionHandlers.before_agent_start({}, ctx).message.content, /NOT SELECTED/);
  runtime.task = task;
  activeTools = [];
  let disabledToolHandler;
  listener({ serverName: server, origin: "direct", claim: (candidate) => { disabledToolHandler = candidate; return true; } });
  assert.equal(disabledToolHandler(), "deny", "persistent selection never restores fully disabled tools");
  activeTools = ["mcp", "read"];
  await registry.writeHazeRegistry(cwd, "project", { version: 1, installs: [{ ...item, disabled: true }] });
  assert.match(persistentPluginSelectionError(ctx, server), /停用/);
  await registry.writeHazeRegistry(cwd, "project", { version: 1, installs: [{ ...item, plugin: { ...item.plugin, digest: "stale" } }] });
  assert.match(persistentPluginSelectionError(ctx, server), /更改/);
  await registry.writeHazeRegistry(cwd, "project", { version: 1, installs: [item] });
  await auth.writeRuntimeHazeSession({ ...session, principal: { ...session.principal, subject: "other" } });
  assert.match(persistentPluginSelectionError(ctx, server), /身份/);
  await auth.writeRuntimeHazeSession(session);
  selectionHandlers.session_shutdown();
  assert.equal(broker.size, 0);
  runtime.dispose();
  await auth.writeRuntimeHazeSession({ ...session, principal: { ...session.principal, subject: "other" } });
  assert.equal(await handoff.handoffPluginBrowserResult(event, cwd, "chat", open), undefined);
  assert.throws(() => composer.prepareSelectedPlugins(cwd, "chat", [plugin], skills, "查询"), /不可用/);
  assert.throws(() => composer.taskAllowsClarification(cwd, "chat", task), /身份已变化/);
  resources.clearPluginSnapshot("chat");
});
