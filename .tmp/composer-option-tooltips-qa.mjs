import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const base='http://127.0.0.1:8080';
const modelList=[{provider:'OpenAI',id:'gpt-5',name:'GPT-5'},{provider:'deepseek',id:'deepseek-v4.1-flash',name:'DeepSeek V4.1 Flash'}];
const browser=await chromium.launch({headless:true,executablePath:chromium.executablePath()});
try{
  const context=await browser.newContext({viewport:{width:1280,height:900},locale:'zh-CN'});
  await context.addCookies([{name:'eureka_guest_session',value:'1',url:base}]);
  const page=await context.newPage();
  page.setDefaultTimeout(12000);
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/api/**',async route=>{
    const url=new URL(route.request().url());let data={};
    if(url.pathname==='/api/models')data={models:Object.fromEntries(modelList.map(m=>[m.id,m.name])),modelList,defaultModel:{provider:'OpenAI',modelId:'gpt-5'}};
    if(url.pathname==='/api/sessions')data={sessions:[],runningSessionIds:[]};
    if(url.pathname==='/api/cwd/validate')data={cwd:'E:/Eureka'};
    if(url.pathname==='/api/agent/running')data={runningSessionIds:[]};
    if(url.pathname==='/api/worktrees')data={isGit:false,projectRoot:'E:/Eureka',worktrees:[]};
    if(url.pathname.startsWith('/api/files/'))data={entries:[]};
    await route.fulfill({json:data});
  });
  await page.goto(`${base}/?cwd=E%3A%2FEureka`,{waitUntil:'domcontentloaded'});
  const model=page.getByRole('button',{name:'Change model: GPT-5',exact:true});
  await model.hover();
  const buttonTip=page.locator('[data-slot=tooltip-content]').filter({hasText:'Change model'});
  await buttonTip.waitFor();
  assert.equal(await buttonTip.evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 255, 255)');
  assert.equal(await buttonTip.locator('[data-slot=tooltip-arrow]').count(),0);
  await model.click();
  const popup=page.getByRole('dialog',{name:'筛选模型…',exact:true});
  await popup.waitFor();
  const option=popup.getByRole('option',{name:'DeepSeek V4.1 Flash',exact:true});
  await option.hover();
  const modelTip=page.locator('[data-slot=tooltip-content]').filter({hasText:'DeepSeek V4.1 Flash'});
  await modelTip.waitFor();
  assert.equal(await option.getAttribute('title'),null);
  assert.equal(await option.locator('[title]').count(),0);
  assert.equal(await modelTip.evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 255, 255)');
  assert.ok(await popup.isVisible());
  await page.screenshot({path:'.tmp/composer-model-option-tooltip.png'});
  await option.click();
  await popup.waitFor({state:'hidden'});
  const currentModel=page.getByRole('button',{name:'Change model: DeepSeek V4.1 Flash',exact:true});
  await currentModel.waitFor();
  await currentModel.click();
  const search=popup.getByRole('combobox');
  await search.fill('gpt-5');
  await search.press('Enter');
  await model.waitFor();
  const effort=page.getByRole('button',{name:'更改推理级别',exact:true});
  await effort.click();
  const high=page.getByRole('menuitemradio',{name:'高',exact:true});
  await high.hover();
  const effortTip=page.locator('[data-slot=tooltip-content]').filter({hasText:'高强度推理'});
  await effortTip.waitFor();
  assert.equal(await high.getAttribute('title'),null);
  assert.ok(await page.getByRole('menu').isVisible());
  await page.screenshot({path:'.tmp/composer-reasoning-option-tooltip.png'});
  await high.click();
  await page.getByRole('menu').waitFor({state:'hidden'});
  assert.match(await effort.innerText(),/高/);
  await effort.click();
  assert.equal(await high.getAttribute('aria-checked'),'true');
  await page.keyboard.press('Escape');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({buttonTooltipRestored:true,modelOptionTooltip:true,reasoningOptionTooltip:true,nativeTitlesRemoved:true,selectionPassed:true,keyboardSearchPassed:true,pageErrors:errors}));
}finally{await browser.close();}
